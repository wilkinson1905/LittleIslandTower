// Screenshots of the game screen at phone and desktop sizes: node tools/ui_shots.mjs outDir
import { open } from './drive.mjs';
import { mkdirSync } from 'node:fs';
import { join } from 'node:path';
const dir = process.argv[2] || 'preview/ui';
mkdirSync(dir, { recursive: true });
const sleep = ms => new Promise(r => setTimeout(r, ms));
const page = await open('notut=1');
const ev = page.evaluate;
await sleep(400);
const size = (width, height, mobile) => page.send('Emulation.setDeviceMetricsOverride', { width, height, deviceScaleFactor: 1, mobile });
await size(390, 844, true);
await sleep(500);
await page.shot(join(dir, '1_start.png'));
await ev(`(() => { const G = dollhouse.game; G.advance(120); G.collectAll(); G.advance(60); return 1; })()`);
await sleep(300);
await ev(`document.querySelector('#faces .face:nth-child(1)').click(); 1`);
await sleep(900);
await page.shot(join(dir, '2_card.png'));
await ev(`document.querySelector('#card .good[data-good="cookie"]').click(); 1`);
await sleep(2500);
await page.shot(join(dir, '3_eating.png'));
await ev(`document.querySelector('#card .x').click(); document.querySelector('[data-view="all"]').click(); 1`);
await ev(`(() => { const G = dollhouse.game; for (let i = 0; i < 12; i++) { G.advance(500); G.collectAll(); } G.grow(); G.grow(); return 1; })()`);
await sleep(900);
await page.shot(join(dir, '4_tower.png'));
await ev(`document.getElementById('shopBtn').click(); 1`);
await sleep(200);
await page.shot(join(dir, '4b_shop.png'));
await ev(`document.getElementById('helpBtn').click(); 1`);
await sleep(200);
await page.shot(join(dir, '4c_help.png'));
await ev(`document.getElementById('menuBtn').click(); 1`);
await sleep(200);
await page.shot(join(dir, '5_menu.png'));
await ev(`document.querySelector('#menu .x').click(); 1`);
await size(360, 640, true);
await sleep(400);
await page.shot(join(dir, '6_small.png'));
await size(1280, 720, false);
await sleep(400);
await page.shot(join(dir, '7_desktop.png'));
if (page.logs.length) console.log(page.logs.slice(0, 10).join('\n'));
page.close();
console.log('done');
