"""Turn a Codex sprite delivery into game data: python tools/import_art.py cat
Reads art/final/<name>/{sheet.png,frames.json} and writes src/21_art_<name>.js.
Run it with the sprite-gen venv's python, which has Pillow."""
import json
import sys
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
name = sys.argv[1]
folder = ROOT / "art" / "final" / name
sheet = Image.open(folder / "sheet.png").convert("RGBA")
meta = json.loads((folder / "frames.json").read_text(encoding="utf-8"))
ax, ay = meta["anchor"]

colors = []


def index(px):
    if px[3] == 0:
        return 0
    rgb = px[0] << 16 | px[1] << 8 | px[2]
    if rgb not in colors:
        colors.append(rgb)
    return colors.index(rgb) + 1


states = {}
for state, info in meta["states"].items():
    frames = []
    for x, y, w, h in info["frames"]:
        cell = sheet.crop((x, y, x + w, y + h))
        box = cell.getbbox()
        if box is None:
            raise SystemExit(f"{state}: empty frame")
        x0, y0, x1, y1 = box
        cw, ch = x1 - x0, y1 - y0
        data = "".join(format(index(cell.getpixel((x0 + i, y0 + j))), "x") for j in range(ch) for i in range(cw))
        frames.append([cw, ch, ax - x0, ay - y0, data])
    states[state] = frames
if len(colors) > 15:
    raise SystemExit(f"{len(colors)} colors: one hex digit holds 15")

out = ROOT / "src" / f"21_art_{name}.js"
const = f"ART_{name.upper()}"
out.write_text(
    f"/* Generated by tools/import_art.py from art/final/{name}. Edit the source art, not this file. */\n"
    f"const {const} = {json.dumps({'colors': colors, 'states': states}, separators=(',', ':'))};\n",
    encoding="utf-8", newline="\n")
print(f"{out.name}: {out.stat().st_size / 1024:.1f} KB, {len(states)} states, {len(colors)} colors")
